package com.example.racecore.armor;

/**
 * RaceCore protection categories.
 *
 * UNIVERSAL exists so vanilla "Protection" can participate in the system
 * without forcing you to map it to only one specific category.
 */
public enum ProtectionType {
    UNIVERSAL,
    MELEE,
    PROJECTILE,
    FIRE,
    BLAST,
    MAGIC,
    OVERTIME
}
